/* =====================================================
   HUIDIGE TAAL
===================================================== */

let huidigeTaal =
    localStorage.getItem("horecalogTaal") || "fr";


/* =====================================================
   VERTALING OPHALEN
===================================================== */

function t(sleutel){

    if(
        vertalingen[huidigeTaal] &&
        vertalingen[huidigeTaal][sleutel]
    ){

        return vertalingen[huidigeTaal][sleutel];

    }


    // Terugvallen op Nederlands
    if(
        vertalingen.nl &&
        vertalingen.nl[sleutel]
    ){

        return vertalingen.nl[sleutel];

    }


    // Sleutel tonen als vertaling ontbreekt
    return sleutel;

}


/* =====================================================
   VERTALINGEN TOEPASSEN OP DE PAGINA
===================================================== */

function vertalingenToepassen(){

    /*
       Gewone teksten

       Bijvoorbeeld:

       <h2 data-i18n="mijnHorecazaken">

    */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(
            function(element){

                let sleutel =
                    element.getAttribute(
                        "data-i18n"
                    );


                element.innerHTML =
                    t(sleutel);

            }
        );


    /*
       Placeholders

       Bijvoorbeeld:

       <input
           data-i18n-placeholder="zoekHorecazaak"
       >
    */

    document
        .querySelectorAll(
            "[data-i18n-placeholder]"
        )
        .forEach(
            function(element){

                let sleutel =
                    element.getAttribute(
                        "data-i18n-placeholder"
                    );


                element.placeholder =
                    t(sleutel);

            }
        );

}


/* =====================================================
   TAAL INSTELLEN
===================================================== */

function taalInstellen(taal){

    /*
       Alleen toegestane talen accepteren
    */

    if(!vertalingen[taal]){
        return;
    }


    /*
       Nieuwe taal bewaren
    */

    localStorage.setItem(
        "horecalogTaal",
        taal
    );


    /*
       Volledige pagina opnieuw laden.
       Hierdoor worden ook alle dynamisch
       opgebouwde teksten opnieuw vertaald.
    */

    window.location.reload();

}
